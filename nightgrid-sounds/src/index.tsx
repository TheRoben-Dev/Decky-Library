import { ButtonItem, DropdownItem, PanelSectionRow, SliderField, staticClasses, ToggleField } from "@decky/ui";
import { definePlugin } from "@decky/api";
import { useState } from "react";
import { FaVolumeUp } from "react-icons/fa";
import { getConfig, setConfig } from "./backend";
import { Config, DEFAULT_CONFIG, hookStatus, Mode, otherSoundPlugin, preview, start, stop, update } from "./engine";
import { sectionFactory } from "./section";
import { Cat, CATS, PACKS } from "./sounds";

const Section = sectionFactory("nightgrid-sounds");
const note = { fontSize: "12px", lineHeight: "16px", opacity: 0.75, whiteSpace: "normal" as const };
const warn = { ...note, color: "var(--ng-warn, #FF9F1C)", opacity: 1 };
const MODE_LABEL: Record<Mode, string> = { pack: "Pack", steam: "Steam's", off: "Off" };

// Module state: Steam remounts the panel on every open and after each dropdown.
let cfg: Config = DEFAULT_CONFIG;
let loaded = false;
let saveTimer: number | undefined;

function commit(next: Config, delay = 0) {
  cfg = next;
  update(next);
  window.clearTimeout(saveTimer);
  saveTimer = window.setTimeout(() => { setConfig(next).catch(() => {}); }, delay);
}

function Content() {
  const [c, setC] = useState<Config>(cfg);
  const [previewCat, setPreviewCat] = useState<Cat>("select");
  const set = (patch: Partial<Config>, delay = 0) => { const n = { ...c, ...patch }; setC(n); commit(n, delay); };
  const pack = PACKS.find((p) => p.id === c.pack) ?? PACKS[0];
  const other = otherSoundPlugin();
  const changed = CATS.filter((x) => (c.cats[x.id] ?? "pack") !== "pack");

  return (
    <>
      <Section id="status" title="Sounds" collapsible={false}>
        <PanelSectionRow>
          <ToggleField label="Nightgrid sounds" description={c.enabled ? `${pack.name} · ${Math.round(c.volume * 100)} %` : "Steam's own sounds"}
            checked={c.enabled} onChange={(on) => set({ enabled: on })} />
        </PanelSectionRow>
        {loaded && !hookStatus() && <PanelSectionRow><div style={warn}>This Steam build's sound player wasn't found, so sounds can't be swapped. Steam's own sounds keep playing.</div></PanelSectionRow>}
        {other && <PanelSectionRow><div style={warn}>{other} is installed too. Set its pack to Default (or turn this off) so the two don't fight over the same sounds.</div></PanelSectionRow>}
      </Section>

      <Section id="pack" title="Pack" defaultOpen summary={pack.name}>
        <PanelSectionRow>
          <DropdownItem label="Sound pack" description={pack.about} selectedOption={c.pack} disabled={!c.enabled}
            rgOptions={PACKS.map((p) => ({ data: p.id, label: p.name }))}
            onChange={(o) => { set({ pack: o.data as string }); preview(o.data as string, "select", c.volume); }} />
        </PanelSectionRow>
        <PanelSectionRow>
          <SliderField label="Volume" value={Math.round(c.volume * 100)} min={0} max={100} step={5} showValue
            disabled={!c.enabled} onChange={(v) => set({ volume: v / 100 }, 600)} />
        </PanelSectionRow>
        <PanelSectionRow>
          <DropdownItem label="Preview" selectedOption={previewCat}
            rgOptions={CATS.map((x) => ({ data: x.id, label: x.name }))}
            onChange={(o) => { setPreviewCat(o.data as Cat); preview(c.pack, o.data as Cat, c.volume); }} />
        </PanelSectionRow>
        <PanelSectionRow>
          <ButtonItem layout="below" onClick={() => preview(c.pack, previewCat, c.volume)}>Play again</ButtonItem>
        </PanelSectionRow>
      </Section>

      <Section id="cats" title="Per sound" summary={changed.length ? `${changed.length} changed` : "All from the pack"}>
        <PanelSectionRow><div style={note}>Keep Steam's sound or silence any single one, e.g. turn off the focus tick.</div></PanelSectionRow>
        {CATS.map((x) => (
          <PanelSectionRow key={x.id}>
            <DropdownItem label={x.name} selectedOption={c.cats[x.id] ?? "pack"} disabled={!c.enabled}
              rgOptions={(["pack", "steam", "off"] as Mode[]).map((m) => ({ data: m, label: MODE_LABEL[m] }))}
              onChange={(o) => {
                const cats = { ...c.cats };
                if (o.data === "pack") delete cats[x.id]; else cats[x.id] = o.data as Mode;
                set({ cats });
              }} />
          </PanelSectionRow>
        ))}
        {changed.length > 0 && (
          <PanelSectionRow><ButtonItem layout="below" onClick={() => set({ cats: {} })}>Reset all to the pack</ButtonItem></PanelSectionRow>
        )}
      </Section>

      <Section id="about" title="About" summary="Original synthesized sounds">
        <PanelSectionRow>
          <div style={note}>
            Every sound is generated by the plugin (no audio files) and swapped in as Steam plays its own, so there's
            nothing running in the background. Sounds Steam adds later that aren't mapped stay Steam's.
            Turning this off or removing the plugin brings Steam's sounds straight back.
          </div>
        </PanelSectionRow>
      </Section>
    </>
  );
}

export default definePlugin(() => {
  // Deferred a moment so Steam's sound player exists and boot isn't slowed down.
  const t = window.setTimeout(() => {
    getConfig().then((c) => { cfg = c; }).catch(() => {}).finally(() => { loaded = true; start(cfg); });
  }, 1500);
  return {
    name: "Nightgrid Sounds",
    titleView: <div className={staticClasses.Title}>Nightgrid Sounds</div>,
    content: <Content />,
    icon: <FaVolumeUp />,
    onDismount() { window.clearTimeout(t); window.clearTimeout(saveTimer); stop(); },
  };
});
